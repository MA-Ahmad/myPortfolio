// Writes lib/generated/: the local MDX posts (posts.ts), the block source files the Code tab,
// /blocks/<name>.md and /r/<name>.json show (block-files.ts), and a Prism with every language for
// blog code blocks (prism.js), all as modules the server code imports.
//
// Cloudflare Workers have no project filesystem, so nothing may read these files at request or ISR
// time. `pnpm dev`, `build`, `typecheck` and `cf:build` run this first; the output is not committed.
// Run with Node 22.18+ (it imports blocks/registry.ts through Node's built-in type stripping).
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { BLOCKS } = await import(path.join(root, 'blocks', 'registry.ts'));

const postsDir = path.join(root, 'data', 'posts');
// Sorted like fs.readdirSync, so lists keep the order they had when the posts were read from disk.
const posts = await Promise.all(
  (await readdir(postsDir))
    .filter((file) => file.endsWith('.mdx'))
    .sort()
    .map(async (file) => ({
      slug: file.replace(/\.mdx$/, ''),
      source: await readFile(path.join(postsDir, file), 'utf8')
    }))
);

const blockFiles = {};
for (const block of BLOCKS) {
  blockFiles[block.name] = {};
  for (const file of block.files) {
    blockFiles[block.name][file] = await readFile(path.join(root, 'blocks', block.name, file), 'utf8');
  }
}

const outDir = path.join(root, 'lib', 'generated');
await mkdir(outDir, { recursive: true });
await writeFile(
  path.join(outDir, 'posts.ts'),
  `// Generated by scripts/generate-content.mjs. Do not edit; it is rewritten on every build.

/** data/posts/*.mdx, frontmatter included, sorted by file name. */
export const LOCAL_POSTS: { slug: string; source: string }[] = ${JSON.stringify(posts, null, 2)};
`
);
await writeFile(
  path.join(outDir, 'block-files.ts'),
  `// Generated by scripts/generate-content.mjs. Do not edit; it is rewritten on every build.

/** blocks/<name>/<file> for every file listed in blocks/registry.ts, keyed by block then file. */
export const BLOCK_FILES: Record<string, Record<string, string>> = ${JSON.stringify(blockFiles, null, 2)};
`
);

const files = Object.values(blockFiles).reduce((n, block) => n + Object.keys(block).length, 0);
console.log(`generate-content: ${posts.length} posts → lib/generated/posts.ts, ${files} block files → lib/generated/block-files.ts`);

// lib/generated/prism.js: a Prism with every language, for blog code blocks (lib/remark-prism.ts).
// remark-prism built this at runtime by reading prismjs from disk and running it with `vm` in jsdom,
// none of which a Worker has. Here the same sources are inlined, in the order remark-prism loaded
// them, into a function whose scope hides the globals Prism probes (window, self, global, module),
// so each call returns an isolated Prism that never touches the shared one lib/block-source.ts uses.
const require = createRequire(import.meta.url);
const prismDir = path.dirname(require.resolve('prismjs/package.json'));
const components = require('prismjs/components.json');
const getLoader = require('prismjs/dependencies');
const prismCore = await readFile(path.join(prismDir, 'prism.js'), 'utf8');

// Languages prism.js defines itself; remark-prism skipped these when loading the rest.
const context = vm.createContext({});
vm.runInContext(`${prismCore}\nthis.__loaded = Object.keys(Prism.languages);`, context);
const loaded = context.__loaded;
const order = [];
getLoader(components, Object.keys(components.languages).filter((l) => l !== 'meta'), loaded).load((lang) => {
  order.push(lang);
});
// Every name or alias remark-prism treated as a known language.
const languages = Object.entries(components.languages)
  .filter(([name]) => name !== 'meta')
  .reduce((memo, [name, { alias }]) => memo.concat(name).concat(alias).filter(Boolean), []);

const componentSources = await Promise.all(
  order.map(async (lang) => {
    const source = await readFile(path.join(prismDir, 'components', `prism-${lang}.min.js`), 'utf8');
    return `\t// prism-${lang}\n\ttry {\n${source}\n\t} catch (err) {\n\t\tconsole.error(err);\n\t}`;
  })
);

const prismOut = path.join(outDir, 'prism.js');
await writeFile(
  prismOut,
  `/* eslint-disable */
// Generated by scripts/generate-content.mjs from prismjs ${require('prismjs/package.json').version}. Do not edit.

/** Every language name and alias remark-prism highlighted. */
export const PRISM_LANGUAGES = ${JSON.stringify(languages)};

/** A fresh, isolated Prism with prism.js and every language component loaded. */
export function createPrism() {
\tvar window, self, document, WorkerGlobalScope, importScripts, global, module, exports;
${prismCore}
${componentSources.join('\n')}
\treturn Prism;
}
`
);
console.log(`generate-content: prism.js + ${order.length} languages → ${path.relative(root, prismOut)}`);
